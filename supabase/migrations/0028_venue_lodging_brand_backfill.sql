-- 사우나우(SAUNAU) — 숙박 브랜드 상호 재분류 백필
-- PostgreSQL (Supabase). 0027 이후 적용.
-- 적용: Supabase Dashboard > SQL Editor 에 그대로 붙여넣기
-- ============================================================
--
-- 배경: venue_type='lodging' 은 "호텔/모텔/리조트…" 같은 일반어로만 잡아서,
--   상호에 그 낱말을 안 쓰는 숙박 부속 사우나가 전부 standalone 으로 샜다.
--   실측(2026-08) 약 40건 — 도미인 서울 강남/인사동, 노보텔앰배서더강남,
--   그랜드하얏트서울, 반얀트리사우나, 힐튼 경주, 소노캄·소노벨 각 지점,
--   이비스 스타일 앰배서더, 아난티 앳 부산 코브, 파라다이스시티 씨메르 등.
--
-- lib/ingest/mapToSauna.ts 의 LODGING_BRAND_RE / LODGING_ADDR_RE 와 동일한 신호다.
-- 둘을 함께 고칠 것 — 다음 동기화에서 되돌아가면 안 된다.
--
-- 브랜드 토큰 선정 원칙: 일반 목욕탕 상호와 겹치는 낱말은 넣지 않는다.
--   제외한 것 — 파라다이스·대명·리베라·신라·조선·팰리스·프리마
--     ("파라다이스목욕탕"(군산·예천), "리베라목욕탕"(강릉), "대명목욕탕"(군산),
--      "천지팰리스"(울산), "크라운사우나찜질방"(건도파라다이스 빌딩) 오분류 방지)
--   "하얏트"는 단독으로 쓰지 않고 그랜드/파크/리젠시 접두형만
--     ("하얏트사우나"(함양), "하얏트부산연산 사우나"는 브랜드와 무관한 동네 사우나)
--   "라한"은 도로명 "청라한내로"에 걸려 제외.
--
-- 안전장치: lodging 이 아닌 행만 대상. standalone 뿐 아니라 community 도 옮긴다
--   (classifyVenue() 가 숙박형 우선이므로 "쉐라톤제주스포츠센터사우나"는 lodging 이 맞다).

update public.saunas
   set venue_type = 'lodging'
 where venue_type <> 'lodging'
   and (
     name ~* '도미인|dormy|노보텔|머큐어|이비스|앰배서더|쉐라톤|웨스틴|메리어트|코트야드|라마다|베스트웨스턴|인터컨티넨탈|소피텔|힐튼|hilton|반얀트리|아난티|워커힐|인스파이어|시그니엘|롯데호텔|신라스테이|파라다이스시티|씨메르|cimer|그랜드하얏트|파크하얏트|하얏트리젠시|소노캄|소노벨|소노펠리체|소노인터내셔널|켄싱턴|스탠포드|드래곤시티|오크우드|서머셋|프레이저'
     or address ~ '소노벨|소노캄|소노펠리체|파라다이스시티|드래곤시티'
   );
